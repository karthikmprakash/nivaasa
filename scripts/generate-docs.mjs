function esc(s) { return s.replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)"); }
function wrap(text, width = 82) {
  const words = text.split(/\s+/); const lines = []; let line = "";
  for (const w of words) { if ((line + " " + w).trim().length > width) { lines.push(line.trim()); line = w; } else line += " " + w; }
  if (line.trim()) lines.push(line.trim());
  return lines;
}
function makePdf(title, sections) {
  const lines = [];
  let y = 780;
  const content = [];
  content.push("BT /F1 20 Tf 60 790 Td (" + esc("Nivaasa community documents") + ") Tj ET");
  content.push("0.12 0.2 0.4 rg");
  content.push("BT /F1 16 Tf 60 750 Td (" + esc(title) + ") Tj ET");
  y = 720;
  for (const s of sections) {
    content.push("0.15 0.18 0.24 rg BT /F1 11 Tf 60 " + y + " Td (" + esc(s.heading) + ") Tj ET");
    y -= 20;
    content.push("0.32 0.36 0.44 rg");
    for (const paragraph of s.body) {
      for (const line of wrap(paragraph, 88)) {
        if (y < 60) break;
        content.push("BT /F1 10 Tf 60 " + y + " Td (" + esc(line) + ") Tj ET");
        y -= 15;
      }
      y -= 6;
    }
    y -= 10;
  }
  content.push("0.55 0.58 0.65 rg BT /F1 8 Tf 60 40 Td (" + esc("Generated by Nivaasa for the demo community. This is a sample document.") + ") Tj ET");
  const stream = content.join("\n");
  const objects = [];
  objects.push("<< /Type /Catalog /Pages 2 0 R >>");
  objects.push("<< /Type /Pages /Kids [3 0 R] /Count 1 >>");
  objects.push("<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>");
  objects.push("<< /Length " + Buffer.byteLength(stream) + " >>\nstream\n" + stream + "\nendstream");
  objects.push("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>");
  let pdf = "%PDF-1.4\n";
  const offsets = [0];
  objects.forEach((obj, i) => { offsets.push(Buffer.byteLength(pdf)); pdf += `${i + 1} 0 obj\n${obj}\nendobj\n`; });
  const xref = Buffer.byteLength(pdf);
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (let i = 1; i <= objects.length; i++) pdf += String(offsets[i]).padStart(10, "0") + " 00000 n \n";
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return pdf;
}

